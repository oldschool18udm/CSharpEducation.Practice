namespace MathLibrary;

public class MathHelper
{
    public static float Add2(float x, float y)
    {
        return x + y;
    }

    public static float Sub2(float x, float y)
    {
        return x - y;
    }

    public static float Mul2(float x, float y)
    {
        return x * y;
    }

    public static float Div2(float x, float y)
    {
        return x / y;
    }
}